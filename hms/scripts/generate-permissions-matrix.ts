/** Generates docs/PERMISSIONS_MATRIX.md from the code so documentation cannot drift. */
import { writeFileSync } from "node:fs";
import { PERMISSIONS } from "../src/server/authz/permissions";
import { ROLE_TEMPLATES } from "../src/server/authz/role-templates";

const abbrev: Record<string, string> = {
  OWNER: "OWN",
  HOSPITAL_ADMIN: "ADM",
  MEDICAL_DIRECTOR: "MD",
  PHYSICIAN: "DR",
  CONSULTANT: "CON",
  NURSING_SUPERVISOR: "NS",
  NURSE: "RN",
  MIDWIFE: "MW",
  RECEPTION: "REC",
  MEDICAL_RECORDS: "MRO",
  LAB_SCIENTIST: "LAB",
  IMAGING: "IMG",
  PHARMACIST: "PH",
  STOREKEEPER: "STR",
  HMO_OFFICER: "HMO",
  CASHIER: "CSH",
  FINANCE: "FIN",
  HR_PAYROLL: "HR",
  SYSTEM_SUPPORT: "SUP",
  AUDITOR: "AUD",
  PATIENT: "PT",
};
const lines: string[] = [
  "# Role & permission matrix",
  "",
  "> Generated by `npm run docs:permissions` from `src/server/authz/*.ts`. Do not edit by hand.",
  "> These are **protective default templates** for review by hospital management before go-live.",
  "> Changes in a running system are made through *Roles & permissions*, which requires a second authorised approver.",
  "",
  "## Role templates",
  "",
  "| Code | Abbrev | Role | MFA required | Description |",
  "| --- | --- | --- | --- | --- |",
  ...ROLE_TEMPLATES.map(
    (t) =>
      `| ${t.code} | ${abbrev[t.code]} | ${t.name} | ${t.requiresMfa ? "Yes" : "No"} | ${t.description} |`,
  ),
  "",
  "## Scope rules (enforced server-side)",
  "",
  "- Every grant is scoped to one branch or explicitly to all branches; grants with neither are ignored (fail closed).",
  "- Grants are effective-dated; expired delegations and revoked roles stop applying on the next request.",
  "- Patient records are visible only in branches where the patient registered or has an appointment/encounter; out-of-scope records appear as *not found*.",
  "- Clinical record access additionally requires a care relationship (care team), `clinical.read.branch_wide`, or an active, reviewed break-glass grant.",
  "- When MFA is enforced, roles marked MFA are suspended until the user enrols.",
  "- Users cannot change their own roles, status or MFA; merges, role changes, guardian verification and break-glass reviews need a second person.",
  "",
  "## Matrix",
  "",
  `| Permission | Sensitivity | ${ROLE_TEMPLATES.map((t) => abbrev[t.code]).join(" | ")} |`,
  `| --- | --- | ${ROLE_TEMPLATES.map(() => ":-:").join(" | ")} |`,
  ...PERMISSIONS.map(
    (p) =>
      `| \`${p.code}\` | ${p.sensitivity} | ${ROLE_TEMPLATES.map((t) => ((t.permissions as string[]).includes(p.code) ? "✓" : "")).join(" | ")} |`,
  ),
  "",
  "## Permission descriptions",
  "",
  ...PERMISSIONS.map((p) => `- \`${p.code}\` (${p.sensitivity}): ${p.description}`),
  "",
];
writeFileSync("docs/PERMISSIONS_MATRIX.md", lines.join("\n"));
console.warn(
  `Wrote docs/PERMISSIONS_MATRIX.md (${PERMISSIONS.length} permissions x ${ROLE_TEMPLATES.length} roles)`,
);
