import type { PermissionCode } from "./permissions";

/**
 * Protective default role templates. Hospital management must review these before go-live.
 * Principles:
 *  - Technical/system administration never implies access to patient health information.
 *  - Executive/owner roles see aggregated dashboards, not charts.
 *  - HR/payroll never see patients; clinicians never see payroll.
 *  - Approvals that move money or change access are split from the requesting role.
 */
export interface RoleTemplate {
  code: string;
  name: string;
  description: string;
  kind: "STAFF" | "PORTAL";
  requiresMfa: boolean;
  permissions: PermissionCode[];
}

